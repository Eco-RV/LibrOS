// Generates the contract clients (app-lib/clients) WITHOUT Rust or the Stellar
// CLI, for Vercel and GitHub Actions. Locally `stellar scaffold build` does
// this; here the bindings come from the contract already deployed on the
// network, picked by env var:
//
//   PUBLIC_LIBRO_VISITAS_CONTRACT_ID     production or staging id (docs/FLUJO.md)
//   PUBLIC_STELLAR_RPC_URL               optional, defaults to the testnet RPC
//   PUBLIC_STELLAR_NETWORK_PASSPHRASE    optional, defaults to testnet
//
//   node scripts/ci-clients.mjs          generate (run BEFORE npm install, so
//                                        the client package becomes a workspace)
//   node scripts/ci-clients.mjs build    compile it (run AFTER npm install)
//
// It overwrites the clients from `stellar scaffold`, so outside CI/Vercel it
// needs --force (then run `stellar scaffold build` to get yours back).
import { execSync } from "node:child_process"
import { mkdirSync, writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

// Same version as app-lib's @stellar/stellar-sdk; it ships `stellar-js`.
const SDK = "@stellar/stellar-sdk@16.1.0"
// Client package name (scaffold.yml key) -> env var with its contract id.
const CONTRACTS = {
	"libro-visitas": "PUBLIC_LIBRO_VISITAS_CONTRACT_ID",
}

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const clientsDir = resolve(root, "app-lib/clients")
const args = process.argv.slice(2)
const run = (cmd, cwd = root) => execSync(cmd, { cwd, stdio: "inherit" })

if (args[0] === "build") {
	for (const name of Object.keys(CONTRACTS)) {
		run(`npm run build --workspace app-lib/clients/${name}`)
	}
	process.exit(0)
}

if (!process.env.CI && !process.env.VERCEL && !args.includes("--force")) {
	console.error(
		"ci-clients: this replaces the clients from `stellar scaffold`. Use --force outside CI/Vercel.",
	)
	process.exit(1)
}

const rpcUrl =
	process.env.PUBLIC_STELLAR_RPC_URL || "https://soroban-testnet.stellar.org"
const passphrase =
	process.env.PUBLIC_STELLAR_NETWORK_PASSPHRASE ||
	"Test SDF Network ; September 2015"
const missing = Object.values(CONTRACTS).filter((v) => !process.env[v])
if (missing.length) {
	console.error(`ci-clients: missing env vars: ${missing.join(", ")}`)
	process.exit(1)
}

mkdirSync(clientsDir, { recursive: true })
for (const [name, envVar] of Object.entries(CONTRACTS)) {
	const id = process.env[envVar]
	console.log(`ci-clients: ${name} <- ${id}`)
	run(
		`npx -y -p ${SDK} stellar-js generate --contract-id ${id} --rpc-url ${rpcUrl} --network testnet --contract-name ${name} --output-dir app-lib/clients/${name} --overwrite`,
	)
}

// Same shape as the index.ts that `stellar scaffold` writes: app-lib/env.ts
// reads the network from `options`.
const pascal = (s) => s.replace(/(^|[-_])(\w)/g, (_, __, c) => c.toUpperCase())
const camel = (s) => pascal(s).replace(/^./, (c) => c.toLowerCase())
const names = Object.keys(CONTRACTS)
const index = [
	"// AUTO-GENERATED by scripts/ci-clients.mjs — do not edit.",
	"",
	...names.map(
		(n) => `import { Client as ${pascal(n)} } from "./${n}/dist/index.js"`,
	),
	"",
	"export const options = {",
	`\tnetworkPassphrase: ${JSON.stringify(passphrase)},`,
	`\trpcUrl: ${JSON.stringify(rpcUrl)},`,
	"\tallowHttp: false,",
	"\tpublicKey: undefined,",
	"}",
	...names.flatMap((n) => [
		"",
		`export const ${camel(n)} = new ${pascal(n)}({`,
		"\t...options,",
		`\tcontractId: "${process.env[CONTRACTS[n]]}",`,
		"})",
	]),
	"",
].join("\n")
writeFileSync(resolve(clientsDir, "index.ts"), index)
console.log("ci-clients: app-lib/clients/index.ts written")
